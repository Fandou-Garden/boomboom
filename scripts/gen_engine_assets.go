//go:build ignore

// gen_engine_assets generates the two data modules the pure-JS engine needs:
//
//	dist/js/engine/rng-cooked.js    Go math/rand rngCooked[607] table, copied
//	                                from $GOROOT/src/math/rand/rng.go so the JS
//	                                port is bit-identical to rand.New(NewSource(s)).
//	dist/js/engine/crater-masks.js  alpha bitmasks of the three original crater
//	                                PNGs, produced with the same image/png decode
//	                                and A <= 100 rule as server/game/terrain.go.
//
// Run from the repository root:  go run scripts/gen_engine_assets.go
package main

import (
	"bytes"
	"encoding/base64"
	"fmt"
	"image"
	_ "image/png"
	"os"
	"path/filepath"
	"regexp"
	"runtime"
	"strings"
)

func must(err error) {
	if err != nil {
		panic(err)
	}
}

func writeFile(path, content string) {
	must(os.MkdirAll(filepath.Dir(path), 0o755))
	must(os.WriteFile(path, []byte(content), 0o644))
	fmt.Printf("wrote %s (%d bytes)\n", path, len(content))
}

func genRNG() {
	src := filepath.Join(runtime.GOROOT(), "src", "math", "rand", "rng.go")
	raw, err := os.ReadFile(src)
	must(err)
	text := string(raw)
	re := regexp.MustCompile(`rngCooked \[rngLen\]int64 = \[\.\.\.\]int64\{([\s\S]*?)\n\t\}`)
	m := re.FindStringSubmatch(text)
	if m == nil {
		panic("rngCooked literal not found in " + src)
	}
	nums := regexp.MustCompile(`-?\d+`).FindAllString(m[1], -1)
	if len(nums) != 607 {
		panic(fmt.Sprintf("want 607 rngCooked values, got %d", len(nums)))
	}
	lines := make([]string, 0, 2+len(nums)/4+2)
	lines = append(lines,
		"// Generated by scripts/gen_engine_assets.go from "+src+". Edit neither by hand.",
		"// Copy of Go math/rand rngCooked; see src/math/rand/rng.go and gen_cooked.go.",
		"// BigInt literals: these are int64 values and must not round-trip through Number.",
		"export const RNG_COOKED = [")
	row := make([]string, 0, 4)
	for i, n := range nums {
		row = append(row, n+"n")
		if len(row) == 4 || i == len(nums)-1 {
			lines = append(lines, "  "+strings.Join(row, ", ")+",")
			row = row[:0]
		}
	}
	lines = append(lines, "];", "")
	writeFile(filepath.Join("dist", "js", "engine", "rng-cooked.js"), strings.Join(lines, "\n"))
}

func genCraters() {
	var b strings.Builder
	b.WriteString("// Generated by scripts/gen_engine_assets.go from dist/assets/crater-*.png.\n")
	b.WriteString("// Alpha bitmask (MSB-first rows, 1 = alpha > 100), identical to\n")
	b.WriteString("// server/game/terrain.go decodeCraterArt. Base64 payload per art id.\n")
	b.WriteString("export const CRATER_MASKS = {\n")
	for _, id := range []string{"50", "401", "4"} {
		path := filepath.Join("dist", "assets", "crater-"+id+".png")
		raw, err := os.ReadFile(path)
		must(err)
		img, _, err := image.Decode(bytes.NewReader(raw))
		must(err)
		bnd := img.Bounds()
		w, h := bnd.Dx(), bnd.Dy()
		mask := make([]byte, w*h)
		for y := 0; y < h; y++ {
			for x := 0; x < w; x++ {
				_, _, _, a := img.At(bnd.Min.X+x, bnd.Min.Y+y).RGBA()
				if uint8(a>>8) > 100 {
					mask[y*w+x] = 1
				}
			}
		}
		packed := make([]byte, (w*h+7)/8)
		for i, v := range mask {
			if v != 0 {
				packed[i/8] |= 1 << uint(7-i%8)
			}
		}
		fmt.Printf("  crater %s: %dx%d\n", id, w, h)
		fmt.Fprintf(&b, "  '%s': { w: %d, h: %d, bits: '%s' },\n", id, w, h,
			base64.StdEncoding.EncodeToString(packed))
	}
	b.WriteString("};\n")
	writeFile(filepath.Join("dist", "js", "engine", "crater-masks.js"), b.String())
}

func main() {
	genRNG()
	genCraters()
}
